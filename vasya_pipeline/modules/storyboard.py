"""Раскадровка и сценарий для озвучки Дядей Васей."""
from .analyze import ask

VASYA = ("Дядя Вася, 50 лет, бывалый прораб. Говорит просто, с юмором и самоиронией, "
         "по-свойски, без мата. Рассказывает про ошибки в стройке.")


def make_storyboard(text):
    prompt = f"""Сделай раскадровку для видео без живого человека (ИИ-аватар + анимации). Русский язык.
Для каждой сцены: номер, длительность (сек), что на экране, что говорит Вася, тип анимации.
Сцен 6-10.

ТЕКСТ:
{text[:10000]}"""
    return ask(prompt)


def make_script(text):
    prompt = f"""Персонаж: {VASYA}
Перепиши материал как сценарий озвучки для YouTube-канала «Вася Знает»:
цепляющее начало, 3-5 ошибок с шутками, вывод и призыв подписаться.
Только текст, который Вася произносит вслух. Русский язык.

МАТЕРИАЛ:
{text[:10000]}"""
    return ask(prompt)
